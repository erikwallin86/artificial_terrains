"""Generate ``artificial_terrains/constructors.py`` from the module classes.

    python -m artificial_terrains.utils.generate_constructors          # write
    python -m artificial_terrains.utils.generate_constructors --check  # verify
"""
import os
import sys

from ..modules.module import Module
from ..modules.modules import MODULES, module_files

TARGET = os.path.join(
    os.path.dirname(os.path.dirname(__file__)), "constructors.py")

RESERVED = {"run", "get_terrain", "get_terrains", "configs"}


def render():
    entries = []
    for mod in module_files:
        short = mod.__name__.rsplit(".", 1)[-1]
        for name, cls in MODULES.items():
            if cls.__module__ != mod.__name__:
                continue
            assert name not in RESERVED, f"{name} clashes with package API"
            # Loops are configured through start(), the rest through __call__
            method = "start" if cls.start is not Module.start else "__call__"
            entries.append((name, f"{short}.{name}.{method}"))

    imports = sorted({ref.split(".")[0] for _, ref in entries})
    lines = [
        '"""Typed module constructors, e.g. ``Gaussian(width=5)``.',
        "",
        "GENERATED by artificial_terrains/utils/generate_constructors.py,",
        "do not edit by hand.",
        '"""',
        "from .module_call import constructor",
        f"from .modules import {', '.join(imports)}",
        "",
        "__all__ = [",
        *[f"    {name!r}," for name, _ in entries],
        "]",
        "",
        *[f"{name} = constructor({name!r}, {ref})" for name, ref in entries],
        "",
    ]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        with open(TARGET) as f:
            if f.read() != text:
                sys.exit(f"{TARGET} is out of date, regenerate it")
        print("constructors.py is up to date")
        return
    with open(TARGET, "w") as f:
        f.write(text)
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
