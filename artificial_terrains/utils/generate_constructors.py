"""Generate ``constructors.py`` and ``constructors.pyi`` from the modules.

    python -m artificial_terrains.utils.generate_constructors          # write
    python -m artificial_terrains.utils.generate_constructors --check  # verify

The .py builds the runtime constructors. The .pyi repeats each module's
signature explicitly, for editors that can't infer it through ParamSpec
(e.g. Jedi, used by elpy and pylsp).
"""
import ast
import builtins
import inspect
import os
import sys
import textwrap
import types
import typing

from ..modules.generating_function import Generative
from ..modules.module import Module
from ..modules.modules import MODULES, module_files
from .artificial_shapes import FUNCTIONS

PACKAGE_DIR = os.path.dirname(os.path.dirname(__file__))
PACKAGE = "artificial_terrains"

RESERVED = {"run", "get_terrain", "get_terrains", "configs"}

HEADER = [
    '"""Typed module constructors, e.g. ``Gaussian(width=5)``.',
    "",
    "GENERATED by artificial_terrains/utils/generate_constructors.py,",
    "do not edit by hand.",
    '"""',
]


def get_entries():
    """(constructor name, module file short name, method, function)."""
    entries = []
    for mod in module_files:
        short = mod.__name__.rsplit(".", 1)[-1]
        for name, cls in MODULES.items():
            if cls.__module__ != mod.__name__:
                continue
            assert name not in RESERVED, f"{name} clashes with package API"
            # Loops are configured through start(), the rest through __call__
            method = "start" if cls.start is not Module.start else "__call__"
            func = inspect.unwrap(getattr(cls, method))
            entries.append((name, short, method, func))
    return entries


def render_py(entries):
    imports = sorted({short for _, short, _, _ in entries})
    return "\n".join([
        *HEADER,
        "from .module_call import constructor",
        f"from .modules import {', '.join(imports)}",
        "",
        "__all__ = [",
        *[f"    {name!r}," for name, *_ in entries],
        "]",
        "",
        *[f"{name} = constructor({name!r}, {short}.{name}.{method})"
          for name, short, method, _ in entries],
        "",
    ])


def find_def(func):
    """The ast FunctionDef of func and its file's source."""
    path = inspect.getsourcefile(func)
    with open(path) as f:
        source = f.read()
    line = func.__code__.co_firstlineno
    for node in ast.walk(ast.parse(source)):
        if (isinstance(node, ast.FunctionDef) and node.name == func.__name__
                and line in [node.lineno]
                + [d.lineno for d in node.decorator_list]):
            return node, source
    raise LookupError(f"definition of {func.__qualname__} not found")


# Pipe data and bookkeeping: never set by hand, so left out of the stub
HIDDEN = {"terrain_temp", "terrain_prim", "call_number", "call_total",
          "path_points"}
# Generative parameters kept for the shape modules (per-call overrides)
SHAPE_SETTINGS = ("size", "grid_size", "resolution", "extent")


def module_aliases(source):
    """Module-level ``Name = <expr>`` assignments, by name."""
    return {node.targets[0].id: node.value
            for node in ast.parse(source).body
            if isinstance(node, ast.Assign) and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)}


def get_params(func, imports):
    """{name: (kind, annotation text, default text)}, self excluded.

    Type aliases defined in func's file are written out in full, so the
    editor shows e.g. ``tuple[float, float, float, float] | list[float]``
    rather than ``Extent_``.
    """
    node, source = find_def(func)
    aliases = module_aliases(source)

    class Inline(ast.NodeTransformer):
        def visit_Name(self, n):
            if n.id in aliases:
                return self.visit(ast.parse(
                    ast.unparse(aliases[n.id]), mode="eval").body)
            add_import(n.id, func, imports)
            return n

    def annotation(arg):
        if arg.annotation is None:
            return ""
        tree = ast.parse(ast.get_source_segment(source, arg.annotation),
                         mode="eval").body
        return ast.unparse(Inline().visit(tree))

    def default_text(default):
        if default is None:
            return None
        try:
            value = ast.literal_eval(default)
        except ValueError:
            return "..."
        # Empty containers are internal placeholders: just say "has default"
        if isinstance(value, (list, tuple, dict)) and not value:
            return "..."
        return ast.get_source_segment(source, default)

    a = node.args
    params = {}
    pos_defaults = [None] * (len(a.args) - len(a.defaults)) + list(a.defaults)
    for arg, d in list(zip(a.args, pos_defaults))[1:]:
        if arg.arg not in HIDDEN:
            params[arg.arg] = ("pos", annotation(arg), default_text(d))
    if a.vararg:
        params[a.vararg.arg] = ("*", "", None)
    for arg, d in zip(a.kwonlyargs, a.kw_defaults):
        if arg.arg not in HIDDEN:
            params[arg.arg] = ("kw", annotation(arg), default_text(d))
    if a.kwarg:
        params[a.kwarg.arg] = ("**", "", None)
    return params


def shape_params(cls, imports):
    """Signature for a Generative subclass, from its shape function.

    Shows the shape's own parameters and defaults (e.g. Crater's
    depth_ratio) instead of Generative's catch-all **kwargs.
    """
    generative = get_params(inspect.unwrap(Generative.__call__), imports)
    shape = get_params(FUNCTIONS[cls.function_name].__init__, imports)
    params = {"default": generative["default"]}
    for name, (_, ann, default) in shape.items():
        if name in generative and generative[name][1]:
            ann = generative[name][1]  # Feature types: one value or a list
        if not name.startswith("_") and name not in ("args", "kwargs"):
            params[name] = ("kw", ann, default)
    for name in SHAPE_SETTINGS:
        params[name] = generative[name]
    return params


def render_params(params):
    parts, star = [], False
    for name, (kind, ann, default) in params.items():
        if kind == "*":
            parts.append(f"*{name}")
            star = True
            continue
        if kind == "**":
            parts.append(f"**{name}")
            continue
        if kind == "kw" and not star:
            parts.append("*")
            star = True
        text = name + (f": {ann}" if ann else "")
        if default is not None:
            text += f" = {default}" if ann else f"={default}"
        parts.append(text)
    return parts


def add_import(name, func, imports):
    """Record the import that makes ``name`` (used in func's file) visible."""
    if hasattr(builtins, name):
        return
    obj = func.__globals__[name]
    if isinstance(obj, types.ModuleType):
        line = f"import {obj.__name__} as {name}"
    elif getattr(typing, name, None) is obj:
        line = f"from typing import {name}"
    else:
        module = func.__module__.removeprefix(PACKAGE)
        line = f"from {module} import {name}"
    previous = imports.setdefault(name, line)
    assert previous == line, f"{name} imported from two places"


def render_pyi(entries):
    imports = {}
    defs = []
    for name, _, _, func in entries:
        cls = MODULES[name]
        if issubclass(cls, Generative) and cls.function_name:
            parts = render_params(shape_params(cls, imports))
            doc = inspect.getdoc(FUNCTIONS[cls.function_name])
        else:
            parts = render_params(get_params(func, imports))
            doc = inspect.getdoc(func)
        one_line = f"def {name}({', '.join(parts)}) -> ModuleCall:"
        if len(one_line) <= 79:
            header = one_line
        else:
            header = "\n".join(
                [f"def {name}("] + [f"    {p}," for p in parts]
                + [") -> ModuleCall:"])
        lines = [header]
        if doc:
            doc = doc.replace('"""', "'''")
            lines.append(textwrap.indent(f'"""{doc}\n"""', "    "))
        lines.append("    ...")
        defs += ["\n".join(lines), ""]

    clashes = set(imports) & {name for name, *_ in entries}
    assert not clashes, f"type names clash with constructors: {clashes}"

    return "\n".join([
        *HEADER,
        "from .module_call import ModuleCall",
        *sorted(set(imports.values())),
        "",
        "__all__ = [",
        *[f"    {name!r}," for name, *_ in entries],
        "]",
        "",
        "",
        *defs,
    ]).rstrip("\n") + "\n"


def main():
    entries = get_entries()
    outputs = {
        os.path.join(PACKAGE_DIR, "constructors.py"): render_py(entries),
        os.path.join(PACKAGE_DIR, "constructors.pyi"): render_pyi(entries),
    }
    check = "--check" in sys.argv
    for path, text in outputs.items():
        if check:
            with open(path) as f:
                if f.read() != text:
                    sys.exit(f"{path} is out of date, regenerate it")
            print(f"{os.path.basename(path)} is up to date")
        else:
            with open(path, "w") as f:
                f.write(text)
            print(f"wrote {path}")


if __name__ == "__main__":
    main()
